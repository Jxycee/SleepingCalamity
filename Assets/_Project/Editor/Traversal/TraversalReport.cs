// World traversal scan: REPORT.md and the top-down maps. Maps are drawn from the scan's grid data (no camera, no GPU): 1 px = one 0.25 m cell (scaled up
// for small Cellars floors), north up. Colours: grey shades = walkable floor of the main area (lighter = higher), dark grey = ground or obstacles with no
// walkable floor, blue-grey = walkable floor cut off from the main area, purple = stuck pockets, orange = narrow, light orange = tight gaps, red = blocked
// intended path or unreachable target, yellow = walk-through mesh, cyan = invisible collider, magenta = hole, thin blue = intended lines, green = stairs;
// targets are green dots (reached) or red rings (unreachable).
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using UnityEngine;

namespace SleepingCalamity.EditorTools
{
    public sealed class TraversalReport
    {
        readonly HeroCapsule hero;
        readonly List<TraversalIssue> issues = new List<TraversalIssue>();
        readonly List<(string name, int targets, int reached, int paths, int stairs, float main, float secs)> spaces = new List<(string, int, int, int, int, float, float)>();
        public List<string> Coverage = new List<string>(); public List<uint> Seeds = new List<uint>();
        public readonly Dictionary<int, int> MapSeed = new Dictionary<int, int>();
        public float Seconds; public string Commit = "?";
        public int Total => issues.Count;

        public TraversalReport(HeroCapsule hero) { this.hero = hero; }

        public void Add(ScanResult r)
        {
            issues.AddRange(r.Issues);
            spaces.Add((r.Space.Name, r.Space.Targets.Count, r.Space.Targets.Count(t => t.Reached), r.Space.Paths.Count, r.Stairs, r.MainArea, r.Seconds));
        }

        static readonly Regex Digits = new Regex(@"[_ ]?\(?-?\d+\)?(?=$|_)");
        static string Leaf(string path) { if (string.IsNullOrEmpty(path)) return ""; int i = path.LastIndexOf('/'); return i < 0 ? path : path.Substring(i + 1); }
        static string Base(string name) { string n = name; for (int i = 0; i < 4; i++) { string m = Digits.Replace(n, ""); if (m == n) break; n = m; } return n; }
        static string RoomKey(string plan) { if (string.IsNullOrEmpty(plan)) return ""; if (plan.StartsWith("room ")) { int k = plan.IndexOf(" rot "); return k > 0 ? plan.Substring(0, k) : plan; } return plan.StartsWith("corridor") ? "corridor" : plan; }
        static string F(float v) => float.IsInfinity(v) ? "-" : v.ToString("0.00");
        static string V(Vector3 p) => $"({p.x:0.0}, {p.y:0.0}, {p.z:0.0})";
        static string Esc(string s) => (s ?? "").Replace("|", "/").Replace("\n", " ");
        static string Src(TraversalIssue i) => string.IsNullOrEmpty(i.Source) ? (string.IsNullOrEmpty(i.Object) ? "" : "-") : "`" + i.Source + "`";
        static string Measure(TraversalIssue i) => i.Limit > 0f || i.Measured > 0f ? $"{F(i.Measured)} {i.Unit} vs {F(i.Limit)} {i.Unit}" : "";

        // Cellars issues of one cause recur over many seeds: group them by floor, kind, room and object.
        sealed class Group { public string Key; public List<TraversalIssue> Items = new List<TraversalIssue>(); public TraversalIssue Worst; public int Seeds; }

        List<Group> CellarGroups(IEnumerable<TraversalIssue> src)
        {
            var d = new Dictionary<string, Group>();
            foreach (TraversalIssue i in src)
            {
                string key = $"F{i.Floor}|{i.Kind}|{RoomKey(i.Plan)}|{Base(Leaf(i.Object))}|{(i.Kind == IssueKind.Unreachable ? Base(i.Group) : i.Group.StartsWith("door") || i.Group.StartsWith("corridor") ? "" : Base(i.Group))}";
                if (!d.TryGetValue(key, out Group g)) d[key] = g = new Group { Key = key };
                g.Items.Add(i);
            }
            foreach (Group g in d.Values)
            {
                g.Worst = g.Items.OrderByDescending(x => x.Score).First();
                g.Seeds = g.Items.Select(x => x.Seed).Distinct().Count();
            }
            return d.Values.OrderByDescending(g => g.Worst.Score + g.Seeds * 20f).ToList();
        }

        public string Markdown()
        {
            var sb = new StringBuilder();
            var town = issues.Where(i => i.Seed < 0).ToList();
            var cellar = issues.Where(i => i.Seed >= 0).ToList();
            var kinds = System.Enum.GetValues(typeof(IssueKind)).Cast<IssueKind>().ToList();
            string[] townVariants = town.Select(i => i.Variant).Distinct().ToArray();
            if (townVariants.Length == 0) townVariants = new[] { "Ruined", "Rebuilt" };
            int cellarFloors = Seeds.Count;

            sb.AppendLine("# World traversal scan");
            sb.AppendLine();
            sb.AppendLine($"Generated by `SleepingCalamity.EditorTools.TraversalScan.RunAll` on commit `{Commit}` ({System.DateTime.UtcNow:yyyy-MM-dd HH:mm} UTC, {Seconds / 60f:0} min). Re-run: `bash Tools/cloud/unity.sh exec --method SleepingCalamity.EditorTools.TraversalScan.RunAll --out <scratch>`.");
            sb.AppendLine();
            sb.AppendLine($"Hero capsule (from `{HeroCapsule.PrefabPath}`'s CharacterController): {hero}.");
            sb.AppendLine($"Spaces: Hollowmere {string.Join(" + ", townVariants)}; Cellars floors 1-4 x {cellarFloors} seeds ({string.Join(", ", Seeds)}).");
            if (Coverage.Count > 0) sb.AppendLine("Seed coverage: " + string.Join("; ", Coverage) + ".");
            sb.AppendLine();

            // ------------------------------------------------------------ summary
            sb.AppendLine("## Summary");
            sb.AppendLine();
            sb.Append("| Kind |"); foreach (string v in townVariants) sb.Append($" Hollowmere {v} |"); for (int f = 1; f <= 4; f++) sb.Append($" Cellars F{f} (issues / seeds) |"); sb.AppendLine();
            sb.Append("|---|"); foreach (string _ in townVariants) sb.Append("---|"); for (int f = 1; f <= 4; f++) sb.Append("---|"); sb.AppendLine();
            foreach (IssueKind k in kinds)
            {
                int any = issues.Count(i => i.Kind == k);
                if (any == 0) continue;
                sb.Append($"| {k} |");
                foreach (string v in townVariants) sb.Append($" {town.Count(i => i.Kind == k && i.Variant == v)} |");
                for (int f = 1; f <= 4; f++) { var fi = cellar.Where(i => i.Kind == k && i.Floor == f).ToList(); sb.Append($" {fi.Count} / {fi.Select(i => i.Seed).Distinct().Count()} |"); }
                sb.AppendLine();
            }
            sb.Append("| **Total** |"); foreach (string v in townVariants) sb.Append($" **{town.Count(i => i.Variant == v)}** |");
            for (int f = 1; f <= 4; f++) { var fi = cellar.Where(i => i.Floor == f).ToList(); sb.Append($" **{fi.Count} / {fi.Select(i => i.Seed).Distinct().Count()}** |"); }
            sb.AppendLine(); sb.AppendLine();
            sb.AppendLine("Reachability per space: " + string.Join("; ", spaces.Where(s => !s.name.StartsWith("Cellars")).Select(s => $"{s.name} {s.reached}/{s.targets} targets, {s.paths} lines, {s.stairs} stairs, main area {s.main:0} m²"))
                + (spaces.Any(s => s.name.StartsWith("Cellars")) ? $"; Cellars {spaces.Where(s => s.name.StartsWith("Cellars")).Sum(s => s.reached)}/{spaces.Where(s => s.name.StartsWith("Cellars")).Sum(s => s.targets)} targets over {spaces.Count(s => s.name.StartsWith("Cellars"))} floors" : "") + ".");
            sb.AppendLine();

            // ------------------------------------------------------------ worst 10
            sb.AppendLine("## Worst 10");
            sb.AppendLine();
            var worst = new List<(TraversalIssue i, string extra)>();
            foreach (TraversalIssue i in town) worst.Add((i, ""));
            foreach (Group g in CellarGroups(cellar)) worst.Add((g.Worst, $" Recurs on {g.Seeds} seed(s)."));
            int rank = 1;
            foreach (var (i, extra) in worst.OrderByDescending(w => w.i.Score + (w.extra.Length > 0 ? 0 : 0)).Take(10))
                sb.AppendLine($"{rank++}. **{i.Kind}**, {i.Where} at {V(i.Pos)}{(string.IsNullOrEmpty(i.Plan) ? "" : " (" + i.Plan + ")")}: {Esc(i.Detail)}. {Measure(i)}.{extra}{(string.IsNullOrEmpty(i.Object) ? "" : " Object `" + i.Object + "`")}{(string.IsNullOrEmpty(i.Source) ? "" : ", likely source `" + i.Source + "`")}.");
            sb.AppendLine();

            // ------------------------------------------------------------ town tables
            foreach (string v in townVariants)
            {
                var list = town.Where(i => i.Variant == v).OrderByDescending(i => i.Score).ToList();
                sb.AppendLine($"## Hollowmere {v} ({list.Count} issues)");
                sb.AppendLine();
                sb.AppendLine($"Map: `maps/Hollowmere_{v}.png`.");
                sb.AppendLine();
                Table(sb, list, 250, false);
            }

            // ------------------------------------------------------------ cellar tables
            for (int f = 1; f <= 4; f++)
            {
                var groups = CellarGroups(cellar.Where(i => i.Floor == f)).ToList();
                sb.AppendLine($"## Cellars F{f} ({cellar.Count(i => i.Floor == f)} issues in {groups.Count} groups over {Seeds.Count} seeds)");
                sb.AppendLine();
                if (MapSeed.TryGetValue(f, out int ms)) sb.AppendLine($"Map: `maps/Cellars_F{f}.png` (seed {ms}, the floor with the most issues).");
                sb.AppendLine();
                sb.AppendLine("| # | Kind | Seeds | Example (seed, position, plan) | Measured vs limit | Detail | Object | Likely source |");
                sb.AppendLine("|---|---|---|---|---|---|---|---|");
                int n = 0;
                foreach (Group g in groups)
                {
                    if (++n > 150) { sb.AppendLine($"| | ... {groups.Count - 150} more groups | | | | | | |"); break; }
                    TraversalIssue i = g.Worst;
                    string seeds = string.Join(", ", g.Items.Select(x => x.Seed).Distinct().Take(6)) + (g.Seeds > 6 ? ", ..." : "");
                    sb.AppendLine($"| {n} | {i.Kind} | {g.Seeds} ({seeds}) | s{i.Seed} {V(i.Pos)} {Esc(i.Plan)} | {Measure(i)} | {Esc(i.Detail)} | `{Esc(Leaf(i.Object))}` | {Src(i)} |");
                }
                sb.AppendLine();
            }

            sb.AppendLine("## Method and limits");
            sb.AppendLine();
            sb.AppendLine("- NavMesh: baked from physics colliders (triggers left out) with an agent of the hero's radius, height, step offset and slope limit (voxel 0.1 m), so reachability is \"walk there and back\". Jumps don't count for reachability; for stuck pockets the hero escapes if the climb is at most step offset + jump height.");
            sb.AppendLine("- Narrow: the capsule plus half the comfort margin doesn't fit, and the free width from thin capsule casts along four axes is below diameter + margin. Blocked: the bare capsule doesn't fit on the line (\"widest fit\" is the largest capsule that does).");
            sb.AppendLine("- Walk-through and invisible checks compare the colliders against the visible meshes (temporary MeshColliders on a spare layer). Soft dressing (foliage, ivy, cloth, lights, hanging signs, lanterns, water, decals) is skipped on purpose.");
            sb.AppendLine("- Hollowmere has no player spawn yet (M6 S3 adds the dive hub), so its largest walkable area counts as the main area. Doors of rebuilt buildings are closed boxes: a door counts as reached when the hero can stand within 1.5 m of it.");
            sb.AppendLine("- Likely source: the first builder line that names the object (searched in Editor/Builders, Presentation/Cellars, Core/Cellars, Core/Town). Treat it as a pointer, not proof.");
            return sb.ToString();
        }

        void Table(StringBuilder sb, List<TraversalIssue> list, int cap, bool seeds)
        {
            sb.AppendLine("| # | Kind | Position | Measured vs limit | Detail | Plan | Object | Likely source |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|");
            int n = 0;
            foreach (TraversalIssue i in list)
            {
                if (++n > cap)
                {
                    var rest = list.Skip(cap).GroupBy(x => x.Kind).Select(g => g.Count() + " " + g.Key);
                    sb.AppendLine($"| | ... {list.Count - cap} more ({string.Join(", ", rest)}) | | | | | | |"); break;
                }
                sb.AppendLine($"| {n} | {i.Kind}{(i.Samples > 1 ? $" (x{i.Samples})" : "")} | {V(i.Pos)} | {Measure(i)} | {Esc(i.Detail)} | {Esc(i.Plan)} | `{Esc(i.Object)}` | {Src(i)} |");
            }
            sb.AppendLine();
        }

        // ---------------------------------------------------------------------------------------------------------------- maps
        public static void WriteMap(ScanResult r, string path)
        {
            WalkGrid g = r.Grid;
            if (g == null) return;
            int scale = Mathf.Max(1, Mathf.Min(4, 960 / Mathf.Max(g.W, g.H)));
            var px = new Color32[g.W * g.H];
            float minY = float.MaxValue, maxY = float.MinValue;
            for (int i = 0; i < px.Length; i++) if (g.HasMain(i)) { float y = g.C0[i] == g.Main ? g.Y0[i] : g.Y1[i]; minY = Mathf.Min(minY, y); maxY = Mathf.Max(maxY, y); }
            float span = Mathf.Max(0.5f, maxY - minY);
            for (int i = 0; i < px.Length; i++)
            {
                ushort f = g.Flags[i];
                Color32 c = new Color32(22, 22, 26, 255);
                if ((f & WalkGrid.FGround) != 0) c = new Color32(70, 70, 76, 255);
                if (g.HasAny(i) && !g.HasMain(i)) c = new Color32(110, 135, 175, 255);
                if (g.HasMain(i))
                {
                    float y = g.C1[i] == g.Main ? g.Y1[i] : g.Y0[i];
                    byte v = (byte)Mathf.RoundToInt(140 + 90 * Mathf.Clamp01((y - minY) / span));
                    c = new Color32(v, v, v, 255);
                }
                if ((f & WalkGrid.FStair) != 0) c = Lerp(c, new Color32(90, 190, 100, 255), 0.45f);
                if ((f & WalkGrid.FPath) != 0) c = Lerp(c, new Color32(70, 120, 230, 255), 0.55f);
                if ((f & WalkGrid.FIsland) != 0) c = new Color32(110, 135, 175, 255);
                if ((f & WalkGrid.FTight) != 0) c = new Color32(255, 205, 110, 255);
                if ((f & WalkGrid.FWalkThrough) != 0) c = new Color32(240, 225, 40, 255);
                if ((f & WalkGrid.FInvisible) != 0) c = new Color32(40, 220, 230, 255);
                if ((f & WalkGrid.FNarrow) != 0) c = new Color32(255, 140, 0, 255);
                if ((f & WalkGrid.FStuck) != 0) c = new Color32(160, 50, 210, 255);
                if ((f & WalkGrid.FHole) != 0) c = new Color32(230, 0, 150, 255);
                if ((f & WalkGrid.FBlocked) != 0) c = new Color32(230, 25, 25, 255);
                px[i] = c;
            }
            int W = g.W * scale, H = g.H * scale;
            var big = new Color32[W * H];
            for (int z = 0; z < H; z++) for (int x = 0; x < W; x++) big[z * W + x] = px[(z / scale) * g.W + x / scale];
            void Dot(Vector3 p, Color32 c, int rad, bool ring)
            {
                int cx = Mathf.FloorToInt((p.x - g.MinX) / g.Cell * scale), cz = Mathf.FloorToInt((p.z - g.MinZ) / g.Cell * scale);
                int rr = rad * Mathf.Max(1, scale / 2 + 1);
                for (int dz = -rr; dz <= rr; dz++)
                    for (int dx = -rr; dx <= rr; dx++)
                    {
                        int d2 = dx * dx + dz * dz;
                        if (d2 > rr * rr || ring && d2 < (rr - 2) * (rr - 2)) continue;
                        int x = cx + dx, z = cz + dz;
                        if (x >= 0 && z >= 0 && x < W && z < H) big[z * W + x] = c;
                    }
            }
            foreach (TraversalIssue i in r.Issues.Where(i => i.Kind == IssueKind.StairToNowhere || i.Kind == IssueKind.Stuck)) Dot(i.Pos, i.Kind == IssueKind.Stuck ? new Color32(160, 50, 210, 255) : new Color32(230, 25, 25, 255), 5, true);
            foreach (TraversalTarget t in r.Space.Targets) Dot(t.Pos, t.Reached ? new Color32(40, 200, 70, 255) : new Color32(230, 25, 25, 255), t.Reached ? 2 : 5, !t.Reached);
            if (r.Space.Spawn.HasValue) Dot(r.Space.Spawn.Value, new Color32(255, 255, 255, 255), 3, false);
            var tex = new Texture2D(W, H, TextureFormat.RGBA32, false);
            tex.SetPixels32(big); tex.Apply(false);
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllBytes(path, tex.EncodeToPNG());
            Object.DestroyImmediate(tex);
        }

        static Color32 Lerp(Color32 a, Color32 b, float t) => Color32.Lerp(a, b, t);
    }
}
